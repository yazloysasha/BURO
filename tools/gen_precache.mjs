// Regenerates precache-manifest.js. Bumps BURO_VERSION whenever any precached file changes.
// Usage: node tools/gen_precache.mjs
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, computeList, computeHash, readManifest } from './precache-lib.mjs';

const list = computeList();
const missing = list.filter((f) => !fs.existsSync(path.join(ROOT, f)));
if (missing.length) {
  console.error('missing files:\n' + missing.join('\n'));
  process.exit(1);
}
const hash = computeHash(list);
const prev = readManifest();
const version = prev && prev.hash === hash ? prev.version : (prev ? prev.version : 0) + 1;
const out =
  '// Generated by tools/gen_precache.mjs - do not edit.\n' +
  `self.BURO_VERSION = ${version};\n` +
  `self.BURO_HASH = '${hash}';\n` +
  `self.BURO_PRECACHE = ${JSON.stringify(list.map((f) => './' + f), null, 0).replace(/","/g, '",\n"')};\n`;
fs.writeFileSync(path.join(ROOT, 'precache-manifest.js'), out);
const bytes = list.reduce((s, f) => s + fs.statSync(path.join(ROOT, f)).size, 0);
console.log(`buro-v${version} ${hash}: ${list.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
